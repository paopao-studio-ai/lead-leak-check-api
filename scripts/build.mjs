// Writes openapi.json and a single-file bundle (dist/worker.js) for the Cloudflare dashboard editor.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import OPENAPI from "../src/openapi.js";

writeFileSync(new URL("../openapi.json", import.meta.url), JSON.stringify(OPENAPI, null, 2) + "\n");

const strip = (src) => src.replace(/^import .*;\n/gm, "");
const rules = strip(readFileSync(new URL("../src/rules.js", import.meta.url), "utf8")).replace(/^export (const|function|class) /gm, "$1 ");
const openapi = readFileSync(new URL("../src/openapi.js", import.meta.url), "utf8").replace("export default {", "const OPENAPI = {");
const worker = strip(readFileSync(new URL("../src/worker.js", import.meta.url), "utf8")).replace(/^export function /gm, "function ");
mkdirSync(new URL("../dist/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../dist/worker.js", import.meta.url),
  "// GENERATED by scripts/build.mjs: single-file bundle for the Cloudflare dashboard. Edit src/ instead.\n" +
    rules + "\n" + openapi + "\n" + worker,
);
console.log("wrote openapi.json and dist/worker.js");

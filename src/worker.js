// Lead Leak Check HTTP API: Cloudflare Worker (ES module). No dependencies, no storage, no outbound calls.
import { checkConfig, checkDescription, analyzeHistory, rulesCatalog, InputError } from "./rules.js";
import OPENAPI from "./openapi.js";

const VERSION = "0.1.0";
const MAX_BODY = 1_000_000; // bytes
const DEFAULT_SECRET_HEADERS = "x-rapidapi-proxy-secret,x-origin-key";

const json = (obj, status = 200, extra = {}) =>
  new Response(JSON.stringify(obj, null, 2), {
    status,
    headers: { "content-type": "application/json; charset=utf-8", "cache-control": "no-store", ...extra },
  });
const err = (status, code, message) => json({ error: { code, message } }, status);

function timingSafeEqual(a, b) {
  const ea = new TextEncoder().encode(a), eb = new TextEncoder().encode(b);
  let diff = ea.length ^ eb.length;
  for (let i = 0; i < Math.max(ea.length, eb.length); i++) diff |= (ea[i] ?? 0) ^ (eb[i] ?? 0);
  return diff === 0;
}

export function authorize(request, env) {
  const secret = env.PROXY_SECRET;
  if (!secret) {
    if (String(env.ALLOW_OPEN || "").toLowerCase() === "true") return null;
    return err(503, "not_configured", "PROXY_SECRET is not set on this deployment.");
  }
  const names = String(env.SECRET_HEADERS || DEFAULT_SECRET_HEADERS).split(",").map((s) => s.trim().toLowerCase()).filter(Boolean);
  for (const n of names) {
    const v = request.headers.get(n);
    if (v && timingSafeEqual(v, secret)) return null;
  }
  return err(401, "unauthorized", "Missing or invalid gateway secret header.");
}

async function readBody(request) {
  const len = Number(request.headers.get("content-length") || 0);
  if (len > MAX_BODY) throw new HttpError(413, "payload_too_large", `Body exceeds ${MAX_BODY} bytes.`);
  const buf = await request.arrayBuffer();
  if (buf.byteLength > MAX_BODY) throw new HttpError(413, "payload_too_large", `Body exceeds ${MAX_BODY} bytes.`);
  const text = new TextDecoder().decode(buf);
  const ct = (request.headers.get("content-type") || "").toLowerCase();
  if (ct.includes("application/json")) {
    try { return { json: JSON.parse(text), text }; } catch { throw new HttpError(400, "invalid_json", "Request body is not valid JSON."); }
  }
  return { json: undefined, text };
}

class HttpError extends Error {
  constructor(status, code, message) { super(message); this.status = status; this.code = code; }
}

function footerFor(env) {
  const url = String(env.FOOTER_URL || "").trim();
  return url ? `_Generated by lead-leak-check (MIT). Want a human to map the full pipeline? ${url}_` : "_Generated by lead-leak-check (MIT)._";
}

function shape(report, env, params) {
  const d = report.asDict({ footer: footerFor(env) });
  const md = (params.get("include_markdown") ?? "true").toLowerCase();
  if (md === "false" || md === "0") delete d.report_markdown;
  return d;
}

function parseInterval(v) {
  if (v === null || v === undefined || v === "") return null;
  const n = Number(v);
  if (!Number.isFinite(n) || n <= 0) throw new HttpError(400, "invalid_parameter", "expected_interval_minutes must be a positive number.");
  return n;
}

async function route(request, env) {
  const url = new URL(request.url);
  const path = url.pathname.replace(/\/+$/, "") || "/";
  const method = request.method.toUpperCase();
  const q = url.searchParams;

  if (path === "/health" || path === "/") return json({ ok: true, service: "lead-leak-check-api", version: VERSION });
  if (path === "/openapi.json") return json(OPENAPI);

  if (!path.startsWith("/v1/")) return err(404, "not_found", "Unknown path. See /openapi.json.");
  const denied = authorize(request, env);
  if (denied) return denied;

  if (!["GET", "POST"].includes(method)) return err(405, "method_not_allowed", "Use GET or POST.");

  if (path === "/v1/rules") return json({ rules: rulesCatalog() });

  if (path === "/v1/check") {
    let cfg;
    if (method === "GET") {
      const raw = q.get("config");
      if (!raw) throw new HttpError(400, "missing_parameter", "Query parameter 'config' (a JSON object as a string) is required.");
      try { cfg = JSON.parse(raw); } catch { throw new HttpError(400, "invalid_json", "'config' is not valid JSON."); }
    } else {
      const b = await readBody(request);
      cfg = b.json !== undefined ? b.json : (() => { try { return JSON.parse(b.text); } catch { throw new HttpError(400, "invalid_json", "Body must be a JSON object."); } })();
      if (cfg && typeof cfg === "object" && !Array.isArray(cfg) && cfg.config !== undefined && Object.keys(cfg).length === 1) {
        cfg = typeof cfg.config === "string" ? JSON.parse(cfg.config) : cfg.config;
      }
    }
    return json(shape(checkConfig(cfg), env, q));
  }

  if (path === "/v1/check-description") {
    let text;
    if (method === "GET") text = q.get("text") ?? q.get("description");
    else {
      const b = await readBody(request);
      text = b.json !== undefined ? (b.json?.text ?? b.json?.description) : b.text;
    }
    if (typeof text !== "string") throw new HttpError(400, "missing_parameter", "Provide 'text' (plain-English description of the lead pipeline).");
    return json(shape(checkDescription(text), env, q));
  }

  if (path === "/v1/analyze-history") {
    let csv, interval = q.get("expected_interval_minutes");
    if (method === "GET") csv = q.get("csv");
    else {
      const b = await readBody(request);
      if (b.json !== undefined) { csv = b.json?.csv; interval = b.json?.expected_interval_minutes ?? interval; }
      else csv = b.text;
    }
    if (typeof csv !== "string" || !csv.trim()) throw new HttpError(400, "missing_parameter", "Provide 'csv' (run-history export with a status column).");
    return json(shape(analyzeHistory(csv, parseInterval(interval)), env, q));
  }

  return err(404, "not_found", "Unknown endpoint. See /openapi.json.");
}

export default {
  async fetch(request, env = {}) {
    try {
      return await route(request, env);
    } catch (e) {
      if (e instanceof HttpError) return err(e.status, e.code, e.message);
      if (e instanceof InputError || e instanceof SyntaxError) return err(400, "invalid_input", e.message);
      return err(500, "internal_error", "Unexpected error.");
    }
  },
};
